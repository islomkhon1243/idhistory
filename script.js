let currentLanguage = localStorage.getItem("loveStoryLanguage") || "ru";
if (!translations[currentLanguage]) currentLanguage = "ru";

function t(key) {
  return translations[currentLanguage]?.[key] ?? translations.ru[key] ?? key;
}

function applyLanguage(lang) {
  if (!translations[lang]) return;
  currentLanguage = lang;
  localStorage.setItem("loveStoryLanguage", lang);
  document.documentElement.lang = translations[lang].htmlLang;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (translations[lang][key] !== undefined) {
      el.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const key = el.dataset.i18nHtml;
    if (translations[lang][key] !== undefined) {
      el.innerHTML = translations[lang][key];
    }
  });

  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    const key = el.dataset.i18nAria;
    if (translations[lang][key] !== undefined) {
      el.setAttribute("aria-label", translations[lang][key]);
    }
  });

  document.querySelectorAll(".language-switcher").forEach(switcher => {
    const code = switcher.querySelector(".language-switcher__code");
    if (code) code.textContent = translations[lang].code;

    switcher.querySelectorAll("[data-lang]").forEach(btn => {
      btn.classList.toggle("is-active", btn.dataset.lang === lang);
    });
  });

  // Keep dynamic music state correct after changing language.
  if (typeof isPlaying !== "undefined" && document.querySelector("#musicState")) {
    const audioEl = document.querySelector("#audio");
    const hasTrackStarted = Boolean(audioEl && audioEl.getAttribute("src"));
    document.querySelector("#musicState").textContent = hasTrackStarted
      ? (isPlaying ? t("playing") : t("paused"))
      : t("music");
  }

  // If no real playlist title has been loaded yet, translate placeholder.
  const trackEl = document.querySelector("#trackName");
  if (trackEl && trackEl.dataset.i18nDefaultTrack === "true" && !trackEl.dataset.realTrackLoaded) {
    trackEl.textContent = t("defaultTrack");
  }

  // Keep the secret button in its current state.
  const secret = document.querySelector("#secretBtn");
  if (secret) {
    secret.textContent = document.querySelector("#secretMessage")?.classList.contains("is-visible")
      ? t("secretButtonLoved")
      : t("secretButton");
  }
}

function closeLanguageMenus(except = null) {
  document.querySelectorAll(".language-switcher.is-open").forEach(sw => {
    if (sw !== except) {
      sw.classList.remove("is-open");
      sw.querySelector(".language-switcher__button")?.setAttribute("aria-expanded", "false");
    }
  });
}

document.querySelectorAll(".language-switcher").forEach(switcher => {
  const toggle = switcher.querySelector(".language-switcher__button");

  toggle.addEventListener("click", (e) => {
    e.stopPropagation();
    const willOpen = !switcher.classList.contains("is-open");
    closeLanguageMenus(switcher);
    switcher.classList.toggle("is-open", willOpen);
    toggle.setAttribute("aria-expanded", String(willOpen));
  });

  switcher.querySelectorAll("[data-lang]").forEach(btn => {
    btn.addEventListener("click", (e) => {
      e.stopPropagation();
      applyLanguage(btn.dataset.lang);
      closeLanguageMenus();
    });
  });
});

document.addEventListener("click", () => closeLanguageMenus());
document.addEventListener("keydown", e => {
  if (e.key === "Escape") closeLanguageMenus();
});

// Apply saved language immediately after the full script has initialized.
queueMicrotask(() => applyLanguage(currentLanguage));


