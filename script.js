const canvas = document.querySelector("#loveCanvas");
const ctx = canvas.getContext("2d");
let particles = [];

function resizeCanvas() {
  const dpr = Math.min(devicePixelRatio || 1, 2);
  canvas.width = innerWidth * dpr;
  canvas.height = innerHeight * dpr;
  canvas.style.width = `${innerWidth}px`;
  canvas.style.height = `${innerHeight}px`;
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);

  const count = Math.min(90, Math.floor(innerWidth / 14));
  particles = Array.from({ length: count }, () => ({
    x: Math.random() * innerWidth,
    y: Math.random() * innerHeight,
    r: Math.random() * 1.25 + .25,
    a: Math.random() * .42 + .08,
    v: Math.random() * .12 + .03,
    phase: Math.random() * Math.PI * 2
  }));
}

function animateCanvas(t = 0) {
  ctx.clearRect(0, 0, innerWidth, innerHeight);

  particles.forEach(p => {
    p.y -= p.v;
    if (p.y < -10) p.y = innerHeight + 10;

    const alpha = p.a * (.65 + Math.sin(t * .001 + p.phase) * .35);
    ctx.beginPath();
    ctx.fillStyle = `rgba(255,220,232,${alpha})`;
    ctx.arc(p.x, p.y, p.r, 0, Math.PI * 2);
    ctx.fill();
  });

  requestAnimationFrame(animateCanvas);
}

resizeCanvas();
animateCanvas();
window.addEventListener("resize", resizeCanvas);

