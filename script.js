function burstHearts(x, y, amount = 20) {
  for (let i = 0; i < amount; i++) {
    const heart = document.createElement("span");
    heart.className = "heart-particle";
    heart.textContent = Math.random() > .32 ? "♡" : "♥";
    heart.style.left = `${x}px`;
    heart.style.top = `${y}px`;
    heart.style.fontSize = `${12 + Math.random() * 22}px`;
    heart.style.setProperty("--x", `${(Math.random() - .5) * 380}px`);
    heart.style.setProperty("--y", `${-90 - Math.random() * 300}px`);
    heart.style.setProperty("--r", `${(Math.random() - .5) * 160}deg`);
    document.body.appendChild(heart);
    setTimeout(() => heart.remove(), 1800);
  }
}

