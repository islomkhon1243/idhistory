const trackName = document.querySelector("#trackName");
const trackProgress = document.querySelector("#trackProgress");
const musicToggle = document.querySelector("#musicToggle");
const musicState = document.querySelector("#musicState");

let currentTrack = 0;
let isPlaying = false;
let autoNextTimer = null;

document.body.classList.add("is-locked");

function loadTrack(index, autoplay = true) {
  currentTrack = (index + playlist.length) % playlist.length;
  const track = playlist[currentTrack];

  audio.src = track.file;
  trackName.textContent = track.title;
  trackName.dataset.realTrackLoaded = "true";
  trackProgress.style.width = "0%";

  clearTimeout(autoNextTimer);

  if (autoplay) {
    audio.play()
      .then(() => setPlayingState(true))
      .catch(() => setPlayingState(false));
  }

  if (autoNextAfterSeconds > 0) {
    autoNextTimer = setTimeout(() => nextTrack(), autoNextAfterSeconds * 1000);
  }
}

function setPlayingState(state) {
  isPlaying = state;
  playerPlay.textContent = state ? "❚❚" : "▶";
  musicState.textContent = state ? t("playing") : t("paused");
  musicToggle.classList.toggle("is-playing", state);
}

function nextTrack() {
  loadTrack(currentTrack + 1, true);
}

function toggleMusic() {
  if (!audio.src) {
    loadTrack(currentTrack, true);
    return;
  }

  if (audio.paused) {
    audio.play().then(() => setPlayingState(true)).catch(() => {});
  } else {
    audio.pause();
    setPlayingState(false);
  }
}

