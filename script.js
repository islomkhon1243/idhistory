const story = document.querySelector("#story");
const timelineProgress = document.querySelector("#timelineProgress");

function updateTimeline() {
  const rect = story.getBoundingClientRect();
  const viewport = window.innerHeight;
  const total = rect.height + viewport * 0.1;
  const traveled = viewport * 0.55 - rect.top;
  const percent = Math.max(0, Math.min(1, traveled / total));
  timelineProgress.style.height = `${percent * 100}%`;
}

window.addEventListener("scroll", updateTimeline, { passive: true });

